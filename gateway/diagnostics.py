"""Content-free plugin events shared by the pipeline and its execution supervisor."""

from dataclasses import dataclass
import json
import logging
import math
import re
from time import perf_counter
from typing import Any, Callable
from uuid import uuid4


LOGGER = logging.getLogger("gateway.plugin_events")
STAGES = frozenset({"request", "response"})
EVENTS = frozenset({"started", "completed", "failed", "timed_out", "cleanup_failed"})
REASONS = frozenset({"plugin_exception", "invalid_output", "timeout", "worker_exit", "worker_startup", "cleanup_failed"})


def configure_diagnostics() -> None:
    """Use the embedding application's handlers, or emit JSON to stderr by default."""
    if not LOGGER.hasHandlers():
        handler = logging.StreamHandler()
        handler.setFormatter(logging.Formatter("%(message)s"))
        LOGGER.addHandler(handler)
    LOGGER.setLevel(logging.INFO)


def new_request_id() -> str:
    return uuid4().hex


@dataclass(frozen=True)
class HookContext:
    request_id: str
    plugin: str
    stage: str

    def __post_init__(self) -> None:
        if not re.fullmatch(r"[0-9a-f]{32}", self.request_id):
            raise ValueError("request_id must be generated by the gateway")
        if self.stage not in STAGES:
            raise ValueError("unknown hook stage")
        if not isinstance(self.plugin, str) or not self.plugin.isidentifier() or len(self.plugin) > 256:
            raise ValueError("plugin label must be a class identifier")


def emit_hook_event(
    context: HookContext,
    event: str,
    *,
    elapsed_ms: float = 0.0,
    reason: str | None = None,
) -> None:
    """Only these explicit scalar fields can reach the event sink; never log payloads."""
    if event not in EVENTS or (reason is not None and reason not in REASONS):
        raise ValueError("unknown diagnostic event or reason")
    if not math.isfinite(elapsed_ms) or elapsed_ms < 0:
        raise ValueError("elapsed_ms must be finite and nonnegative")
    record = {
        "schema_version": 1,
        "event": event,
        "request_id": context.request_id,
        "plugin": context.plugin,
        "stage": context.stage,
        "elapsed_ms": round(elapsed_ms, 3),
        "reason": reason,
    }
    LOGGER.info(json.dumps(record, separators=(",", ":"), allow_nan=False))


class PluginFailure(Exception):
    def __init__(self, context: HookContext, reason: str):
        self.context = context
        self.reason = reason
        super().__init__(f"plugin {context.plugin} failed during {context.stage} processing")


def run_hook(
    plugin: Any,
    payload: dict[str, Any],
    context: HookContext,
    *,
    emit: Callable[..., None] = emit_hook_event,
    validate: Callable[[dict[str, Any]], None] | None = None,
) -> dict[str, Any]:
    """Instrument one synchronous hook without retaining its exception text."""
    emit(context, "started")
    started = perf_counter()
    try:
        result = getattr(plugin, "process_" + context.stage)(payload)
    except BaseException:
        emit(context, "failed", elapsed_ms=(perf_counter() - started) * 1000, reason="plugin_exception")
        raise PluginFailure(context, "plugin_exception") from None
    if not isinstance(result, dict):
        emit(context, "failed", elapsed_ms=(perf_counter() - started) * 1000, reason="invalid_output")
        raise PluginFailure(context, "invalid_output")
    if validate is not None:
        try:
            validate(result)
        except (TypeError, ValueError, RecursionError):
            emit(context, "failed", elapsed_ms=(perf_counter() - started) * 1000, reason="invalid_output")
            raise PluginFailure(context, "invalid_output") from None
    emit(context, "completed", elapsed_ms=(perf_counter() - started) * 1000)
    return result
